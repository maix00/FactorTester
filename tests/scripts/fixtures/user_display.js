const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
global.window = {};
global.document = {createElement: () => ({})};
vm.runInThisContext(fs.readFileSync('server/manager/web/core/shared-ui.js','utf8'));
global.FTUI = window.FTUI;
const a = 'GTHT@MaxJJW@392452984564';
const b = 'OTHER@MaxJJW@77';
assert.equal(FTUI.userLabel(a), 'MaxJJW');
assert.equal(FTUI.userLabel(a, '新别名'), '新别名');
assert.equal(FTUI.userLabel(a, a), 'MaxJJW');
assert.equal(FTUI.userLabel('user@example.com'), 'user@example.com');
assert.equal(FTUI.userLabel('bad@name@opaque'), 'bad@name@opaque');
assert.equal(FTUI.userLabel('__public_jobs__', '公共因子库'), '公共因子库');
assert.equal(FTUI.userDisplay(a).title, a);
assert.equal(FTUI.userDisplay(b).title, b);
assert.equal(FTUI.userDisplay(a).textContent, FTUI.userDisplay(b).textContent);
assert.equal(FTUI.userDisplay(a, '<img src=x>').textContent, '<img src=x>');
assert.equal(FTUI.userDisplay(a, '<img src=x>').innerHTML, undefined);
vm.runInThisContext(fs.readFileSync('server/manager/web/catalog/factor-model.js','utf8'));
const frozen = {schema_version:2, owner_ref:a};
assert.equal(window.FTFactorModel.owner(frozen),'MaxJJW');
assert.equal(frozen.owner_ref,a);
console.log('user label/display/frozen identity checks passed');
