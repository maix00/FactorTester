/**
 * panels/derived/summary.js — Derived group summary panel (Tab 2, sub-tab "汇总")
 *
 * Phase 4 UI panel. Read-only overview of the selected derived group node,
 * showing: name, type (manual/auto), parent, base group, and all overrides
 * (fee, closeToday, rebalanceMode, productMask).
 *
 * Contract:
 *   GT.state.getActiveDerivedNodeId() → id|null
 *   GT.state.on('activeDerivedNodeChanged', cb)
 *   GT.state.on('derivedGraphChanged', cb)
 *   GT.datamodel.derived_graph.get(id) → node|null
 */

(function() {
    var GT = window.GroupTest;
    if (!GT) throw new Error('GroupTest bootstrap not loaded');
    if (!GT.panels) { GT.panels = {}; }
    if (!GT.panels.derived) { GT.panels.derived = {}; }

    var CONTAINER_ID = 'derived-summary-panel';

    var _mounted = false;

    function $(id) { return document.getElementById(id); }

    function _getNode() {
        var id = GT.state.getActiveDerivedNodeId();
        if (!id) return null;
        return GT.datamodel.derived_graph.get(id);
    }

    function _baseGroupName(node) {
        if (!node || !node.baseGroupId) return '—';
        var bg = GT.datamodel.base_groups.get(node.baseGroupId);
        return (bg && bg.name) ? bg.name : node.baseGroupId;
    }

    function _parentName(node) {
        if (!node || !node.parentId) return '— (顶层)';
        var p = GT.datamodel.derived_graph.get(node.parentId);
        return (p && p.name) ? p.name : node.parentId;
    }

    function _typeLabel(node) {
        if (!node) return '—';
        return node.isAutoGenerated ? '自动生成' : '手动创建';
    }

    // ---------------------------------------------------------------------------
    // Override summaries
    // ---------------------------------------------------------------------------

    function _feeSummary(node) {
        if (!node || !node.feeOverride) return null;
        var f = node.feeOverride;
        var parts = [];
        if (f.mode) parts.push('模式: ' + f.mode);
        if (f.uniformRate !== undefined) parts.push('费率: ' + f.uniformRate);
        if (f.sensitivity !== undefined) parts.push('敏感度: ' + f.sensitivity);
        return parts.length ? parts.join(' | ') : null;
    }

    function _closeTodaySummary(node) {
        if (!node || !node || !node.closeTodayOverride) return null;
        if (node.closeTodayOverride === true) return '平今';
        if (node.closeTodayOverride === false) return '平昨';
        return '覆盖';
    }

    function _rebalanceSummary(node) {
        if (!node || !node.rebalanceModeOverride) return null;
        var map = {
            each_period: '每期再平衡',
            buy_and_hold: '买入持有',
            recycle: '循环再平衡',
        };
        return map[node.rebalanceModeOverride] || node.rebalanceModeOverride;
    }

    function _productsSummary(node) {
        if (!node || !node.productMask || Object.keys(node.productMask).length === 0) return null;
        var keys = Object.keys(node.productMask);
        if (keys.length <= 5) return keys.join(', ');
        return keys.slice(0, 5).join(', ') + ' ... (' + keys.length + ' 个)';
    }

    function _overrideCount(node) {
        if (!node) return 0;
        var c = 0;
        if (node.feeOverride) c++;
        if (node.closeTodayOverride !== undefined && node.closeTodayOverride !== null) c++;
        if (node.rebalanceModeOverride) c++;
        if (node.productMask && Object.keys(node.productMask).length > 0) c++;
        return c;
    }

    // ---------------------------------------------------------------------------
    // Render
    // ---------------------------------------------------------------------------

    function _infoRow(label, value, color) {
        var c = color || '';
        return '<tr><td style="padding:6px 12px;font-size:12px;color:#666;white-space:nowrap;vertical-align:top;">'
            + label + '</td><td style="padding:6px 12px;font-size:13px;' + c + '">' + value + '</td></tr>';
    }

    function _overrideRow(label, value) {
        return '<tr style="background:#fffbeb;">'
            + '<td style="padding:6px 12px;font-size:12px;color:#666;white-space:nowrap;">'
            + '⚡ ' + label + '</td>'
            + '<td style="padding:6px 12px;font-size:13px;color:#d97706;">' + value + '</td></tr>';
    }

    function render() {
        var container = $(CONTAINER_ID);
        if (!container) return;

        var node = _getNode();
        if (!node) {
            container.innerHTML = '<div style="padding:24px;text-align:center;color:#888;">请在「树」中选择一个派生组节点</div>';
            return;
        }

        var ct = _overrideCount(node);

        var html = '';

        // Basic info
        html += '<div style="margin-bottom:16px;">';
        html += '<span style="font-size:16px;font-weight:700;">' + (node.name || node.id) + '</span>';
        html += '<span style="margin-left:8px;font-size:11px;padding:2px 6px;border-radius:4px;'
            + (node.isAutoGenerated ? 'background:#e0f2fe;color:#0369a1;' : 'background:#f0fdf4;color:#15803d;')
            + '">' + _typeLabel(node) + '</span>';
        if (ct > 0) {
            html += '<span style="margin-left:8px;font-size:11px;padding:2px 6px;border-radius:4px;background:#fffbeb;color:#d97706;">' + ct + ' 项覆盖</span>';
        }
        html += '</div>';

        html += '<table style="width:100%;border-collapse:collapse;">';
        html += _infoRow('ID', node.id, 'font-family:monospace;font-size:12px;');
        html += _infoRow('父节点', _parentName(node));
        html += _infoRow('基础组', _baseGroupName(node));

        // Overrides section
        var feeS = _feeSummary(node);
        var ctS = _closeTodaySummary(node);
        var rbS = _rebalanceSummary(node);
        var pdS = _productsSummary(node);

        var hasAnyOverride = feeS || ctS || rbS || pdS;
        if (hasAnyOverride) {
            html += '<tr><td colspan="2" style="padding:10px 12px 4px;font-size:12px;font-weight:600;color:#888;">覆盖配置</td></tr>';
            if (feeS) html += _overrideRow('费率', feeS);
            if (ctS) html += _overrideRow('平今/昨', ctS);
            if (rbS) html += _overrideRow('再平衡', rbS);
            if (pdS) html += _overrideRow('品种', pdS);
        }

        // Days override (generic)
        if (node.daysOverride !== undefined && node.daysOverride !== null) {
            if (!hasAnyOverride) {
                html += '<tr><td colspan="2" style="padding:10px 12px 4px;font-size:12px;font-weight:600;color:#888;">覆盖配置</td></tr>';
                hasAnyOverride = true;
            }
            html += _overrideRow('天数', String(node.daysOverride));
        }

        if (!hasAnyOverride) {
            html += '<tr><td colspan="2" style="padding:16px 12px;text-align:center;color:#aaa;font-size:13px;">无覆盖配置 (全部继承自父节点或基础组)</td></tr>';
        }

        html += '</table>';

        container.innerHTML = html;
    }

    // ---------------------------------------------------------------------------
    // Event handlers
    // ---------------------------------------------------------------------------

    function _onDerivedNodeChanged() { if (_mounted) render(); }
    function _onDerivedGraphChanged() { if (_mounted) render(); }

    // ---------------------------------------------------------------------------
    // Public API
    // ---------------------------------------------------------------------------

    function mount() {
        _mounted = true;
        GT.state.on('activeDerivedNodeChanged', _onDerivedNodeChanged);
        GT.state.on('derivedGraphChanged', _onDerivedGraphChanged);
        render();
    }

    function unmount() {
        _mounted = false;
        GT.state.off('activeDerivedNodeChanged', _onDerivedNodeChanged);
        GT.state.off('derivedGraphChanged', _onDerivedGraphChanged);
    }

    function refresh() { if (_mounted) render(); }

    // ---------------------------------------------------------------------------
    // Export
    // ---------------------------------------------------------------------------

    GT.panels.derived.summary = {
        mount: mount,
        unmount: unmount,
        refresh: refresh,
        render: render,
    };

    GT.log('panels.derived.summary loaded');
})();
