/**
 * panels/derived/tree.js — Derived group tree panel (Tab 2, sub-tab "树")
 *
 * Phase 4 UI panel. Renders derived group tree with indent levels,
 * expand/collapse, node selection, and CRUD via inline forms.
 * All data access through datamodel + state.
 */
(function() {
    var GT = window.GroupTest;
    if (!GT) throw new Error('GroupTest bootstrap not loaded');
    if (!GT.panels) { GT.panels = {}; }
    if (!GT.panels.derived) { GT.panels.derived = {}; }

    // ---------------------------------------------------------------------------
    // Internal state
    // ---------------------------------------------------------------------------

    var _containerId = 'derived-tree';
    var _formId = 'derived-node-form';
    var _mounted = false;
    var _activeId = null;
    var _collapsedIds = {};   // id → true if collapsed

    // ---------------------------------------------------------------------------
    // Helpers
    // ---------------------------------------------------------------------------

    function $(id) { return document.getElementById(id); }

    function escapeHTML(str) {
        if (str === null || str === undefined) return '';
        return String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    }

    /**
     * Count how many registrations reference this derived group.
     */
    function _countRegistrations(nodeId) {
        if (!GT.state._registrations) return 0;
        var regs = GT.state._registrations;
        var count = 0;
        Object.keys(regs).forEach(function(key) {
            var entries = regs[key];
            if (entries && Array.isArray(entries)) {
                for (var i = 0; i < entries.length; i++) {
                    if (entries[i].derivedGroupId === nodeId) {
                        count++;
                    }
                }
            }
        });
        return count;
    }

    /**
     * Get badge text for a node (auto/manual + registrations count).
     */
    function _nodeBadge(node) {
        var parts = [];
        if (node.isAutoGenerated) {
            parts.push('🤖 自动');
        } else {
            parts.push('✏️ 手动');
        }
        var regCount = _countRegistrations(node.id);
        if (regCount > 0) {
            parts.push('已登记x' + regCount);
        }
        return parts.join(' · ');
    }

    // ---------------------------------------------------------------------------
    // Form: Add / Edit node
    // ---------------------------------------------------------------------------

    function _openForm(parentId, editData) {
        _closeForm();

        var isEdit = !!editData;
        var title = isEdit ? '编辑派生组' : '新增派生组';

        var baseGroupOptions = '';
        if (!isEdit) {
            var baseGroups = GT.datamodel.base_groups.getAll();
            for (var i = 0; i < baseGroups.length; i++) {
                baseGroupOptions += '<option value="' + escapeHTML(baseGroups[i].id) + '">'
                    + escapeHTML(baseGroups[i].name) + '</option>';
            }
        }

        var html = '<div id="' + _formId + '" style="position:fixed;top:0;left:0;width:100%;height:100%;background:rgba(0,0,0,0.4);display:flex;align-items:center;justify-content:center;z-index:10001;">';
        html += '<div style="background:#fff;border-radius:8px;padding:24px;min-width:420px;max-width:520px;box-shadow:0 8px 32px rgba(0,0,0,0.2);">';
        html += '<h3 style="margin:0 0 16px 0;">' + title + '</h3>';
        html += '<form onsubmit="return false;">';

        // Name field
        html += '<label style="display:block;margin-bottom:12px;">';
        html += '<span style="display:block;font-size:13px;margin-bottom:4px;">名称 <span style="color:red;">*</span></span>';
        html += '<input type="text" id="dnf_name" value="' + escapeHTML(isEdit ? editData.name : '') + '" style="width:100%;padding:6px;border:1px solid #ddd;border-radius:4px;" required>';
        html += '</label>';

        // Base group (only for new nodes)
        if (!isEdit) {
            html += '<label style="display:block;margin-bottom:12px;">';
            html += '<span style="display:block;font-size:13px;margin-bottom:4px;">基础组 <span style="color:red;">*</span></span>';
            html += '<select id="dnf_baseGroupId" style="width:100%;padding:6px;border:1px solid #ddd;border-radius:4px;">';
            html += '<option value="">— 请选择 —</option>';
            html += baseGroupOptions;
            html += '</select>';
            html += '</label>';
        }

        // Parent node (for new nodes, pre-filled)
        if (!isEdit && parentId) {
            var parentNode = GT.datamodel.derived_graph.get(parentId);
            var parentName = parentNode ? parentNode.name : parentId;
            html += '<label style="display:block;margin-bottom:12px;">';
            html += '<span style="display:block;font-size:13px;margin-bottom:4px;">父节点</span>';
            html += '<input type="text" value="' + escapeHTML(parentName) + '" readonly style="width:100%;padding:6px;border:1px solid #eee;border-radius:4px;background:#f6f8fa;color:#666;">';
            html += '</label>';
        }

        // Buttons
        html += '<div style="text-align:right;margin-top:20px;">';
        html += '<button type="button" id="dnf_cancel" style="margin-right:8px;padding:6px 16px;border:1px solid #d0d5dd;border-radius:4px;background:#fff;cursor:pointer;">取消</button>';
        html += '<button type="submit" id="dnf_save" style="padding:6px 16px;border:none;border-radius:4px;background:#0969da;color:#fff;cursor:pointer;">保存</button>';
        html += '</div>';

        html += '</form></div></div>';
        document.body.insertAdjacentHTML('beforeend', html);

        // Ensure form field mirrors edit data (some interaction concerns work with element.value)
        if (isEdit) {
            $('dnf_name').value = editData.name;
        }

        $('dnf_cancel').addEventListener('click', _closeForm);
        $('dnf_save').addEventListener('click', function() {
            var name = $('dnf_name').value.trim();
            if (!name) { alert('请输入名称'); return; }

            try {
                if (isEdit) {
                    GT.datamodel.derived_graph.update(editData.id, { name: name });
                } else {
                    var bgId = $('dnf_baseGroupId').value;
                    if (!bgId) { alert('请选择基础组'); return; }
                    GT.datamodel.derived_graph.add({
                        name: name,
                        baseGroupId: bgId,
                        parentId: parentId || null
                    });
                }
                _closeForm();
            } catch (err) {
                alert('操作失败: ' + err.message);
            }
        });

        // Enter to save
        $('dnf_name').addEventListener('keydown', function(e) {
            if (e.key === 'Enter') { $('dnf_save').click(); }
        });
    }

    function _closeForm() {
        var form = $(_formId);
        if (form) {
            // Clean up form child elements so fresh form gets clean elements
            ['dnf_name', 'dnf_baseGroupId', 'dnf_cancel', 'dnf_save'].forEach(function(id) {
                var el = document.getElementById(id);
                if (el) { el.remove(); }
            });
            form.remove();
        }
    }

    // ---------------------------------------------------------------------------
    // Tree rendering
    // ---------------------------------------------------------------------------

    /**
     * Render one tree node and its children recursively.
     */
    function _renderNode(node, level, htmlArr) {
        var indent = level * 24;
        var childCount = (node.children || []).length;
        var isCollapsed = _collapsedIds[node.id] || false;
        var isActive = node.id === _activeId;

        var rowStyle = isActive ? 'background:#e8f4fd;' : '';
        var rowClass = isActive ? 'grouptest-row-active' : '';

        htmlArr.push('<tr class="derived-tree-node ' + rowClass + '" data-dg-id="' + escapeHTML(node.id) + '" data-level="' + level + '" style="cursor:pointer;border-bottom:1px solid #e8eaed;' + rowStyle + '">');

        // Expand/Collapse toggle
        htmlArr.push('<td style="padding:6px 8px;width:32px;text-align:center;">');
        if (childCount > 0) {
            var toggleIcon = isCollapsed ? '▶' : '▼';
            htmlArr.push('<span class="derived-toggle" data-dg-id="' + escapeHTML(node.id) + '" style="cursor:pointer;font-size:10px;">' + toggleIcon + '</span>');
        }
        htmlArr.push('</td>');

        // Name with indent
        htmlArr.push('<td style="padding:6px 8px;min-width:200px;">');
        htmlArr.push('<span style="display:inline-block;width:' + indent + 'px;"></span>');
        htmlArr.push('<span class="derived-node-name">' + escapeHTML(node.name) + '</span>');
        htmlArr.push('</td>');

        // Badge
        htmlArr.push('<td style="padding:6px 8px;font-size:11px;color:#666;">');
        htmlArr.push(_nodeBadge(node));
        htmlArr.push('</td>');

        // Actions
        htmlArr.push('<td style="padding:6px 8px;text-align:right;white-space:nowrap;">');
        htmlArr.push('<button class="derived-add-child-btn" data-dg-id="' + escapeHTML(node.id) + '" style="margin-right:4px;padding:2px 8px;font-size:11px;border:1px solid #d0d5dd;border-radius:3px;background:#fff;cursor:pointer;" title="添加子节点">+子</button>');
        htmlArr.push('<button class="derived-edit-btn" data-dg-id="' + escapeHTML(node.id) + '" style="margin-right:4px;padding:2px 8px;font-size:11px;border:1px solid #d0d5dd;border-radius:3px;background:#fff;cursor:pointer;" title="编辑">✏️</button>');
        htmlArr.push('<button class="derived-del-btn" data-dg-id="' + escapeHTML(node.id) + '" style="padding:2px 8px;font-size:11px;border:1px solid #d0d5dd;border-radius:3px;background:#fff;cursor:pointer;" title="删除">🗑️</button>');
        htmlArr.push('</td>');

        htmlArr.push('</tr>');

        // Render children if not collapsed
        if (!isCollapsed && childCount > 0) {
            for (var i = 0; i < node.children.length; i++) {
                _renderNode(node.children[i], level + 1, htmlArr);
            }
        }
    }

    function render() {
        var container = $(_containerId);
        if (!container) return;

        var tree = GT.datamodel.derived_graph.getTree();

        var htmlArr = [];
        if (tree.length === 0) {
            htmlArr.push('<div style="padding:32px;text-align:center;color:#888;">暂无派生组，请先在「基础组定义」Tab 中创建基础组</div>');
        } else {
            htmlArr.push('<table style="width:100%;border-collapse:collapse;font-size:13px;">');
            htmlArr.push('<thead><tr style="background:#f6f8fa;border-bottom:2px solid #d0d5dd;">');
            htmlArr.push('<th style="padding:6px 8px;width:32px;"></th>');
            htmlArr.push('<th style="padding:6px 8px;text-align:left;">名称</th>');
            htmlArr.push('<th style="padding:6px 8px;text-align:left;">类型</th>');
            htmlArr.push('<th style="padding:6px 8px;text-align:right;">操作</th>');
            htmlArr.push('</tr></thead><tbody>');

            for (var i = 0; i < tree.length; i++) {
                _renderNode(tree[i], 0, htmlArr);
            }

            htmlArr.push('</tbody></table>');
        }

        // Add "new root" button
        htmlArr.push('<div style="padding:12px 0;text-align:left;">');
        htmlArr.push('<button id="derived-add-root-btn" style="padding:4px 12px;font-size:12px;border:1px dashed #d0d5dd;border-radius:4px;background:#fff;cursor:pointer;">+ 新增根节点派生组</button>');
        htmlArr.push('</div>');

        container.innerHTML = htmlArr.join('');
        _bindEvents(container);
    }

    function _bindEvents(container) {
        // Row click → select
        var rows = container.querySelectorAll('.derived-tree-node');
        for (var i = 0; i < rows.length; i++) {
            rows[i].addEventListener('click', function(e) {
                var tag = e.target.tagName;
                var cls = e.target.classList;
                if (tag === 'BUTTON' || (cls && cls.contains('derived-toggle'))) return;
                var id = this.getAttribute('data-dg-id');
                GT.state.setActiveDerivedNodeId(id);
            });
        }

        // Toggle expand/collapse
        var toggles = container.querySelectorAll('.derived-toggle');
        for (var j = 0; j < toggles.length; j++) {
            toggles[j].addEventListener('click', function(e) {
                e.stopPropagation();
                var id = this.getAttribute('data-dg-id');
                _collapsedIds[id] = !_collapsedIds[id];
                render();
            });
        }

        // Add child button
        var addChildBtns = container.querySelectorAll('.derived-add-child-btn');
        for (var k = 0; k < addChildBtns.length; k++) {
            addChildBtns[k].addEventListener('click', function(e) {
                e.stopPropagation();
                var id = this.getAttribute('data-dg-id');
                _openForm(id, null);
            });
        }

        // Edit button
        var editBtns = container.querySelectorAll('.derived-edit-btn');
        for (var m = 0; m < editBtns.length; m++) {
            editBtns[m].addEventListener('click', function(e) {
                e.stopPropagation();
                var id = this.getAttribute('data-dg-id');
                var node = GT.datamodel.derived_graph.get(id);
                if (node) {
                    _openForm(null, node);
                }
            });
        }

        // Delete button
        var delBtns = container.querySelectorAll('.derived-del-btn');
        for (var n = 0; n < delBtns.length; n++) {
            delBtns[n].addEventListener('click', function(e) {
                e.stopPropagation();
                var id = this.getAttribute('data-dg-id');
                var node = GT.datamodel.derived_graph.get(id);
                if (!node) return;

                var msg = node.isAutoGenerated
                    ? '删除"' + node.name + '"将级联删除其所有子节点和相关基础组。确定？'
                    : '确定删除派生组"' + node.name + '"吗？';

                if (confirm(msg)) {
                    try {
                        GT.datamodel.derived_graph.remove(id);
                    } catch (err) {
                        alert('删除失败: ' + err.message);
                    }
                }
            });
        }

        // Add root button
        var addRootBtn = container.querySelector('#derived-add-root-btn');
        if (addRootBtn) {
            addRootBtn.addEventListener('click', function() {
                _openForm(null, null);
            });
        }
    }

    // ---------------------------------------------------------------------------
    // Event handlers
    // ---------------------------------------------------------------------------

    function _onDerivedGraphChanged(data) {
        if (_mounted) { render(); }
    }

    function _onActiveDerivedNodeChanged(data) {
        if (_mounted) {
            _activeId = data.id;
            render();
        }
    }

    // ---------------------------------------------------------------------------
    // Public API
    // ---------------------------------------------------------------------------

    function mount() {
        _mounted = true;

        var container = $(_containerId);
        if (!container) {
            GT.log('panels.derived.tree: container #' + _containerId + ' not found');
            return;
        }

        _activeId = GT.state.getActiveDerivedNodeId();

        GT.state.on('derivedGraphChanged', _onDerivedGraphChanged);
        GT.state.on('activeDerivedNodeChanged', _onActiveDerivedNodeChanged);

        render();
    }

    function unmount() {
        _mounted = false;
        _closeForm();
        GT.state.off('derivedGraphChanged', _onDerivedGraphChanged);
        GT.state.off('activeDerivedNodeChanged', _onActiveDerivedNodeChanged);
    }

    function refresh() {
        if (_mounted) {
            _activeId = GT.state.getActiveDerivedNodeId();
            render();
        }
    }

    // ---------------------------------------------------------------------------
    // Export
    // ---------------------------------------------------------------------------

    GT.panels.derived.tree = {
        mount: mount,
        unmount: unmount,
        refresh: refresh,
        render: render,
        _openForm: _openForm,
        _closeForm: _closeForm,
    };

    GT.log('panels.derived.tree loaded');
})();
